import fs from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export function repository(value) {
  try {
    const url = new URL(value);
    if (url.protocol !== 'https:' || url.hostname !== 'github.com') return null;
    const match = /^\/([\w-]+)\/([\w.-]+)(?:\/|$)/.exec(url.pathname);
    return match ? `${match[1]}/${match[2].replace(/\.git$/, '')}`.toLowerCase() : null;
  } catch { return null; }
}

export function collectRepositories(publications, events) {
  const urls = publications.flatMap((item) => [item.links?.code]);
  for (const item of events) urls.push(item.link, ...Object.values(item.codeLinks || {}), ...Object.values(item.titleLinks || {}));
  return [...new Set(urls.map(repository).filter(Boolean))].sort();
}

export async function updateSnapshot(repos, previous, fetcher = fetch, now = new Date().toISOString()) {
  const repositories = {};
  const failures = [];
  let updated = 0;
  for (const repo of repos) {
    // Preserve the last successful count and its timestamp on failure, including zero.
    const saved = previous.repositories?.[repo];
    if (Number.isSafeInteger(saved?.count) && saved.count >= 0 && Number.isFinite(Date.parse(saved.updatedAt))) repositories[repo] = saved;
    try {
      const response = await fetcher(`https://api.github.com/repos/${repo}`, {
        headers: {
          Accept: 'application/vnd.github+json',
          ...(process.env.GITHUB_TOKEN ? { Authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {})
        },
        signal: AbortSignal.timeout(15000)
      });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const data = await response.json();
      if (!Number.isSafeInteger(data.stargazers_count) || data.stargazers_count < 0) throw new Error('Invalid count');
      repositories[repo] = { count: data.stargazers_count, updatedAt: now };
      updated++;
    } catch (error) { failures.push({ repo, message: error.message }); }
  }
  return { snapshot: { updatedAt: updated ? now : previous.updatedAt || null, repositories }, updated, failures };
}

async function main() {
  const read = async (file) => JSON.parse(await fs.readFile(file, 'utf8'));
  const [nusPubs, smuPubs, nusEvents, smuEvents] = await Promise.all([
    'assets/nus_publications.json', 'assets/smu_publications.json', 'assets/nus_events.json', 'assets/smu_events.json'
  ].map(read));
  let previous = {};
  try { previous = await read('assets/github-stars.json'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const repos = collectRepositories([...nusPubs, ...smuPubs], [...nusEvents, ...smuEvents]);
  const { snapshot, updated, failures } = await updateSnapshot(repos, previous);
  const json = JSON.stringify(snapshot, null, 2);
  await fs.writeFile('assets/github-stars.json', `${json}\n`);
  // A regular script is loaded before rendering, so the first render already has counts.
  await fs.writeFile('assets/js/github-stars-data.js', `// Generated by scripts/update-github-stars.mjs. Do not edit by hand.\nwindow.GitHubStarSnapshot = ${json};\n`);
  console.log(`Updated ${updated}/${repos.length} repositories; saved ${Object.keys(snapshot.repositories).length} counts.`);
  for (const failure of failures) console.warn(`::warning::${failure.repo}: ${failure.message}; keeping any saved count.`);
  if (!updated) throw new Error('No repositories refreshed; the saved snapshot was preserved.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
